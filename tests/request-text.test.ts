// node --experimental-strip-types --test tests/
// Известителното писмо до фирмата: текстът на заявката е без ЕГН, номера на документи, адрес по документа и линкове към снимки.
import assert from "node:assert/strict";
import { test } from "node:test";
import { ownerRequestText } from "../server/request-text.ts";

// Текстът така, както го сглобява index.html (buildText) + снимките (sendBooking) – със синтетични данни
const MESSAGE = [
  "Заявка за наем: Volkswagen Golf 5", "Получаване: 01.03.2027 10:00, доставка до ул. Доставка 5, Пловдив", "Връщане: 03.03.2027 10:00, гр. Пловдив, бул. Дунав 10",
  "Детско столче: да, 1 бр.", "Пътуване в чужбина: не", "Общо за услугите: 61 €. Депозит: 100 €", "Брой дни: 2, цена на ден: 25 €, наем на автомобила: 50 €",
  "", "ПЛАЩАНЕ: По банков път – физическо лице (фактура)", "ДАННИ ЗА ФАКТУРА", "Физическо лице", "Имена: ТЕСТ ТЕСТОВ", "ЕГН: 8001010000", "Адрес: обл. Тест, ул. Документ 9",
  "", "КЛИЕНТ", "Имена: ТЕСТ ТЕСТОВ", "Гражданство: България", "Телефон: +359000000000", "Имейл: test@example.com",
  "", "ДОКУМЕНТ ЗА САМОЛИЧНОСТ", "Вид: лична карта", "Номер: 640000001", "ЕГН: 8001010000", "Дата на издаване: 01.01.2020", "Издаден от: МВР Тест",
  "Област: Тест", "Община: Тест", "Населено място: гр. Тест", "Адрес: ул. Документ 9", "Адрес по документа: обл. Тест, ул. Документ 9",
  "", "ШОФЬОРСКА КНИЖКА", "Номер: 290000001", "Имена: ТЕСТ ТЕСТОВ", "Дата на издаване: 02.02.2021", "Издадена от: МВР Тест",
  "", "Забележка: Моля, обадете се преди доставката.", "", "Език на сайта: BG",
  "", "", "СНИМКИ НА ДОКУМЕНТИТЕ", `Документ за самоличност – лицева страна: https://site.example/api/documents/${"a".repeat(64)}`,
  `Шофьорска книжка – гръб: https://site.example/api/documents/${"b".repeat(64)}`,
].join("\n");

test("махат се ЕГН, номерата на документите, адресът по документа и линковете към снимките", () => {
  const t = ownerRequestText(MESSAGE);
  for (const bad of ["8001010000", "640000001", "290000001", "ул. Документ 9", "МВР Тест", "/api/documents/", "ДОКУМЕНТ ЗА САМОЛИЧНОСТ", "ШОФЬОРСКА КНИЖКА", "СНИМКИ НА ДОКУМЕНТИТЕ", "ЕГН"])
    assert.ok(!t.includes(bad), "остана: " + bad);
});

test("остават данните за резервацията, услугите, плащането и контакта", () => {
  const t = ownerRequestText(MESSAGE);
  for (const ok of ["Volkswagen Golf 5", "доставка до ул. Доставка 5", "Детско столче: да, 1 бр.", "Общо за услугите: 61 €", "ПЛАЩАНЕ: По банков път", "Имена: ТЕСТ ТЕСТОВ", "Телефон: +359000000000", "Имейл: test@example.com", "Забележка: Моля, обадете се", "Език на сайта: BG"])
    assert.ok(t.includes(ok), "липсва: " + ok);
});

test("фирмена фактура: данните на фирмата остават", () => {
  const t = ownerRequestText("ПЛАЩАНЕ: По банков път – фирма (фактура)\nДАННИ ЗА ФАКТУРА\nФирма: Тест ЕООД\nЕИК / Булстат: 000000000\nДДС номер: BG000000000\nАдрес: гр. Тест, ул. Фирмена 1");
  for (const ok of ["Фирма: Тест ЕООД", "ЕИК / Булстат: 000000000", "ДДС номер: BG000000000", "Адрес: гр. Тест, ул. Фирмена 1"]) assert.ok(t.includes(ok), ok);
});

test("ЕГН/ЛНЧ и линк към снимка извън разделите също се махат", () => {
  const t = ownerRequestText(`Ред 1\nЛНЧ: 1000000000\n(ЕГН 8001010000)\nвиж https://x.example/api/documents/${"c".repeat(64)}\nРед 2`);
  assert.equal(t, "Ред 1\nРед 2");
});
