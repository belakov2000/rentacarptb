import { strFromU8, unzipSync } from "fflate";
import { adminJar, check, contractData, finish, freshDb, O, setContext, schema } from "./harness.ts";
import handler from "../../netlify/functions/admin-manual-contracts.mts";
const t = await freshDb("manualcontracts");
t.use();
const base = O + "/api/admin/manual-contracts";
const id = crypto.randomUUID();
const detail = base + "/" + id;
const data = {...contractData("2028-11-01","11:00","2028-11-03","11:00"),carId:"passat",name:"Тестов наемател",rent:60};
const save = (revision:number, name:string) => handler(new Request(detail,{method:"POST",headers:{Origin:O,"Content-Type":"application/json"},body:JSON.stringify({revision,data:{...data,name}})}));
setContext("deploy-preview");
check("Private archive", (await handler(new Request(base))).status === 401);
setContext("deploy-preview",{cookies:adminJar()});
const created = await save(0,data.name);
check("Create without photographs", created.status === 201 && (await created.json()).revision === 1);
check("Stable retry", (await save(0,data.name)).status === 200);
check("Update stored contract", (await save(1,"Променен наемател")).status === 200);
check("Reject stale overwrite", (await save(1,"Стара промяна")).status === 409);
const list = await (await handler(new Request(base))).json();
check("List and fleet", list.rows.some((x:any)=>x.id === id) && list.cars.some((x:any)=>x.id === data.carId));
const word = await handler(new Request(detail+"/file"));
const xml = strFromU8(unzipSync(new Uint8Array(await word.arrayBuffer()))["word/document.xml"]);
check("Edited Word document",xml.includes("Променен наемател"));
const print = await handler(new Request(detail+"/print"));
check("Print version", (await print.text()).includes("Променен наемател"));
check("Separate from reservations", !(await t.db.select().from(schema.bookings)).length);
await finish();
