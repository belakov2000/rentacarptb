// Текстът на заявката от сайта (поле message) за известителното писмо до фирмата – без лични идентификатори.
// Махат се: разделите „ДОКУМЕНТ ЗА САМОЛИЧНОСТ“ (вид, номер, ЕГН, издаване, адрес по документа), „ШОФЬОРСКА КНИЖКА“
// и „СНИМКИ НА ДОКУМЕНТИТЕ“ (линкове към снимките), редове с ЕГН/ЛНЧ навсякъде, адресът в данните за фактура
// на физическо лице (по подразбиране е адресът по документа)
// и всеки останал линк към /api/documents/. Остават автомобилът, периодът, услугите, сумата, плащането, данните за фирмена
// фактура, имената, телефонът, имейлът, забележката и езикът.
// Пълните данни остават за договора (прикачения .docx) и за админ панела след вход. Текстът идва от браузъра,
// затова филтърът е по раздели (блокове, разделени с празен ред) и допълнително по съдържание на всеки ред.
const DROP_SECTIONS = /^(ДОКУМЕНТ ЗА САМОЛИЧНОСТ|ШОФЬОРСКА КНИЖКА|СНИМКИ НА ДОКУМЕНТИТЕ)\s*$/;
// Кирилицата не е „дума“ за \b в JavaScript – краят на думата се проверява изрично
const DROP_LINE = /(^|[\s(])(ЕГН|ЛНЧ|EGN)(?=[\s:/,]|$)|\/api\/documents\//i;
// Данни за фактура на физическо лице: адресът е по подразбиране адресът по документа – също не влиза в писмото
const PERSON_INVOICE = /^Физическо лице\s*$/m;

export function ownerRequestText(message: string) {
  const blocks = String(message || "").replace(/\r\n?/g, "\n").split(/\n\s*\n/);
  return blocks
    .filter((b) => !DROP_SECTIONS.test(b.trim().split("\n")[0].trim()))
    .map((b) => b.split("\n").filter((l) => !DROP_LINE.test(l) && !(PERSON_INVOICE.test(b) && /^Адрес:/.test(l.trim()))).join("\n"))
    .filter((b) => b.trim())
    .join("\n\n");
}

// Сумите в текста идват от браузъра – в писмото до фирмата се заменят със сървърната разбивка (server/pricing.ts → priceLines).
// Махат се редовете със суми и услуги от браузъра навсякъде; блокът „ЦЕНА“ се поставя след първия блок (автомобил и период).
const CLIENT_PRICE_LINE = /^(Общо за услугите|Брой дни|Детско столче|Пътуване в чужбина)\s*:/;
export function withServerPrice(message: string, lines: string[]) {
  const blocks = String(message || "").replace(/\r\n?/g, "\n").split(/\n\s*\n/)
    .map((b) => b.split("\n").filter((l) => !CLIENT_PRICE_LINE.test(l.trim())).join("\n"))
    .filter((b) => b.trim());
  const price = ["ЦЕНА (изчислена от сървъра)", ...lines].join("\n");
  return [...blocks.slice(0, 1), price, ...blocks.slice(1)].join("\n\n");
}
